export function renderTextToMatrix(
  text: string,
  totalCols: number = 52,
  charSpacing: number = 1,
  level: number = 4,
  align: "left" | "center" | "right" = "center",
  offsetWeeks: number = 0
): number[][] {
  const grid: number[][] = Array.from({ length: 7 }, () => Array(totalCols).fill(0));
  if (!text.trim()) return grid;

  const upperText = text.toUpperCase();
  const renderedCols: number[][] = [];

  for (let i = 0; i < upperText.length; i++) {
    const ch = upperText[i];
    const glyph = FONT_5X7[ch] || FONT_5X7["?"];
    const glyphWidth = glyph[0].length;

    for (let c = 0; c < glyphWidth; c++) {
      const colVector = [
        glyph[0][c],
        glyph[1][c],
        glyph[2][c],
        glyph[3][c],
        glyph[4][c],
        glyph[5][c],
        glyph[6][c],
      ];
      renderedCols.push(colVector);
    }

    if (i < upperText.length - 1) {
      for (let s = 0; s < charSpacing; s++) {
        renderedCols.push([0, 0, 0, 0, 0, 0, 0]);
      }
    }
  }

  const contentWidth = renderedCols.length;
  let startCol = 0;

  if (align === "center") {
    startCol = Math.max(0, Math.floor((totalCols - contentWidth) / 2));
  } else if (align === "right") {
    startCol = Math.max(0, totalCols - contentWidth);
  } else {
    startCol = 0;
  }

  startCol += offsetWeeks;

  for (let colOffset = 0; colOffset < renderedCols.length; colOffset++) {
    const targetCol = startCol + colOffset;
    if (targetCol >= 0 && targetCol < totalCols) {
      for (let r = 0; r < 7; r++) {
        if (renderedCols[colOffset][r]) {
          grid[r][targetCol] = level;
        }
      }
    }
  }

  return grid;
}
