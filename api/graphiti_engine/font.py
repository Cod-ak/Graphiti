def render_text_to_matrix(
    text: str,
    total_cols: int = 52,
    char_spacing: int = 1,
    level: int = 4,
    align: str = "left",
    offset_weeks: int = 0
) -> List[List[int]]:
    """
    Renders an ASCII text string onto a 7-row by `total_cols` matrix.
    
    Args:
        text: The string to render (auto-uppercased).
        total_cols: Total columns in graph (default 52).
        char_spacing: Columns between adjacent characters (default 1).
        level: Shading level (1-4) for active pixels.
        align: "left", "center", or "right".
        offset_weeks: Additional horizontal shift (positive = right, negative = left).
        
    Returns:
        7-row x `total_cols` matrix where each cell is 0 or `level`.
    """
    # 7 rows initialized to 0
    grid: List[List[int]] = [[0 for _ in range(total_cols)] for _ in range(7)]
    
    # Assemble glyph columns
    upper_text = text.upper()
    rendered_cols: List[List[int]] = []  # List of 7-element column vectors
    
    for i, ch in enumerate(upper_text):
        glyph = FONT_5X7.get(ch, FONT_5X7.get('?'))
        glyph_width = len(glyph[0])
        
        for col_idx in range(glyph_width):
            col_vector = [glyph[row_idx][col_idx] for row_idx in range(7)]
            rendered_cols.append(col_vector)
            
        # Add spacing column after character if not the last character
        if i < len(upper_text) - 1:
            for _ in range(char_spacing):
                rendered_cols.append([0] * 7)
                
    content_width = len(rendered_cols)
    
    # Calculate starting column
    if align == "center":
        start_col = max(0, (total_cols - content_width) // 2)
    elif align == "right":
        start_col = max(0, total_cols - content_width)
    else:  # left
        start_col = 0
        
    start_col += offset_weeks
    
    # Paint onto grid
    for col_offset, col_data in enumerate(rendered_cols):
        target_col = start_col + col_offset
        if 0 <= target_col < total_cols:
            for row_idx in range(7):
                if col_data[row_idx]:
                    grid[row_idx][target_col] = level
                    
    return grid
